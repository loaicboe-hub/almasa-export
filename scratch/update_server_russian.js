// Update data_store.json
const dsPath = path.join(__dirname, '..', 'database', 'data_store.json');
if (fs.existsSync(dsPath)) {
  const ds = JSON.parse(fs.readFileSync(dsPath, 'utf8'));
  if (Array.isArray(ds.projects)) {
    ds.projects = ds.projects.map(p => {
      const match = ruProjectsData.find(r => r.id === p.id);
      if (match) {
        p.title_ru = match.title_ru;
        p.entity_ru = match.entity_ru;
        p.desc_ru = match.desc_ru;
        p.client_ru = match.entity_ru;
      }
      return p;
    });
    fs.writeFileSync(dsPath, JSON.stringify(ds, null, 2), 'utf8');
    console.log('Updated database/data_store.json with Russian project fields!');
  }
}
